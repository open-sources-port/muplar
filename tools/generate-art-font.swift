// Regenerate the software renderer's ASCII atlas from an Android font.
// Run with swift tools/generate-art-font.swift /path/to/Roboto-Regular.ttf > muplar_font.h
import Foundation
import CoreGraphics
import CoreText

let size: CGFloat = 32
let width = 40
let height = 40
let baseline = 30
let url = URL(fileURLWithPath: CommandLine.arguments[1])
let provider = CGDataProvider(url: url as CFURL)!
let graphicsFont = CGFont(provider)!
let font = CTFontCreateWithGraphicsFont(graphicsFont, size, nil, nil)
var advances: [Int] = []
var atlas: [[UInt8]] = []
for code in 32...126 {
    var character = UniChar(code)
    var glyph: CGGlyph = 0
    CTFontGetGlyphsForCharacters(font, &character, &glyph, 1)
    var advance = CGSize.zero
    CTFontGetAdvancesForGlyphs(font, .horizontal, &glyph, &advance, 1)
    advances.append(Int(advance.width.rounded()))
    var pixels = [UInt8](repeating: 0, count: width * height)
    pixels.withUnsafeMutableBytes { buffer in
        let context = CGContext(data: buffer.baseAddress, width: width, height: height,
            bitsPerComponent: 8, bytesPerRow: width,
            space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue)!
        context.setFillColor(gray: 1, alpha: 1)
        var position = CGPoint(x: 0, y: height - baseline)
        CTFontDrawGlyphs(font, &glyph, &position, 1, context)
    }
    atlas.append(pixels)
}
print("/* Generated by tools/generate-art-font.swift from Roboto-Regular.ttf. */")
print("#ifndef MUPLAR_FONT_HEADER_H\n#define MUPLAR_FONT_HEADER_H\n#include <stdint.h>")
print("#define MUPLAR_FONT_FIRST_CHAR 32\n#define MUPLAR_FONT_LAST_CHAR 126")
print("#define MUPLAR_FONT_NUM_CHARS 95")
print("#define MUPLAR_FONT_W 40\n#define MUPLAR_FONT_H 40")
print("#define MUPLAR_FONT_SIZE 32.0f\n#define MUPLAR_FONT_BASELINE 30.0f")
print("static const uint8_t muplar_font_advances[95] = {")
print(advances.map(String.init).joined(separator: ", "))
print("};\nstatic const uint8_t muplar_font_alpha[95][1600] = {")
for pixels in atlas {
    print("{")
    for row in 0..<height {
        print(pixels[(row * width)..<((row + 1) * width)].map(String.init).joined(separator: ",") + ",")
    }
    print("},")
}
print("};\n#endif")
